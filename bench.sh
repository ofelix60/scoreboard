#!/usr/bin/env bash
# Record build time and image size for one tagged build, so image-size and
# cache changes can be compared across revisions.
#
#   usage: ./bench.sh v1 "what changed"
#
# Appends a row to benchmarks.md (tracked, so the history survives a clone).
set -euo pipefail

TAG=${1:?usage: ./bench.sh <tag> [note]}
NOTE=${2:-}
IMG="scoreboard:$TAG"
OUT="$(dirname "$0")/benchmarks.md"

now()   { python3 -c 'import time; print(time.time())'; }
since() { python3 -c "import time; print(f'{time.time()-$1:.2f}')"; }

t=$(now)
docker build --no-cache -t "$IMG" .
cold=$(since "$t")

t=$(now)
docker build -t "$IMG" .
warm=$(since "$t")

mb=$(( $(docker image inspect "$IMG" --format '{{.Size}}') / 1000000 ))

if [ ! -f "$OUT" ]; then
  printf '# Build benchmarks\n\nGenerated by `bench.sh`.\n\n| date | tag | size | cold build | warm build | note |\n|---|---|---|---|---|---|\n' > "$OUT"
fi

printf '| %s | %s | %sMB | %ss | %ss | %s |\n' \
  "$(date +%F)" "$TAG" "$mb" "$cold" "$warm" "$NOTE" >> "$OUT"
tail -1 "$OUT"
